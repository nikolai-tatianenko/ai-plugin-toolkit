import { LoomError, ReviewTargetSchema, parseWith, type ReviewTarget } from "@ai-plugin-toolkit/core";
import type { LoomStore } from "@ai-plugin-toolkit/storage-sqlite";
import { checklistReport, safeEndpoint } from "@ai-plugin-toolkit/workspace";

export interface ReviewRequest { number: number; url: string; head: string; base: string; }
export interface ReviewAdapter {
  find(): Promise<ReviewRequest | undefined>;
  create(body: string): Promise<ReviewRequest>;
  update(number: number, body: string): Promise<ReviewRequest>;
}

export function saveReviewTarget(store: LoomStore, project: string, name: string, raw: unknown, actor: string, expectedRevision = 0) {
  const target = parseWith(ReviewTargetSchema, raw, "review target");
  return store.documents.put(project, "review.target", name, target, actor, expectedRevision);
}

export function reviewPreview(store: LoomStore, project: string, target: ReviewTarget, checklistIds: string[]) {
  if (checklistIds.length === 0) throw new LoomError("VALIDATION_FAILED", "Select at least one checklist.");
  const sections = checklistIds.map(id => {
    const r = checklistReport(store, project, id);
    if (r.value.archived) throw new LoomError("VALIDATION_FAILED", `Checklist ${id} is archived.`);
    return [
      `### ${r.value.pack.title} (${id})`,
      `Revision: ${r.evaluation.revision ?? "unverified"}. Readiness: ${r.evaluation.readiness.status}.`,
      ...r.evaluation.criteria.map(c => `- [${c.verification === "passed" ? "x" : " "}] ${c.title} — verification: ${c.verification}; disposition: ${c.disposition}`),
    ].join("\n");
  });
  return { ...target, body: [target.body, "## Checklists", ...sections, "Generated by Context Loom. Task closure and human acceptance alone do not establish a technical pass."].filter(Boolean).join("\n\n") };
}

/** Factory boundary allows GitHub, GitLab or another host without changing the domain. */
export function httpReviewAdapter(target: ReviewTarget, token: string, transport: typeof fetch = fetch): ReviewAdapter {
  if (!token) throw new LoomError("CREDENTIALS_MISSING", `Set ${target.tokenEnv} for ${target.provider}.`);
  const base = (target.apiUrl ?? (target.provider === "github" ? "https://api.github.com" : "https://gitlab.com/api/v4")).replace(/\/$/, "");
  safeEndpoint(base);
  const project = target.provider === "github" ? `/repos/${target.repository}/pulls` : `/projects/${encodeURIComponent(target.repository)}/merge_requests`;
  const headers = target.provider === "github" ? { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json" } : { "PRIVATE-TOKEN": token };
  async function api(method: string, suffix: string, body?: unknown): Promise<any> {
    const response = await transport(base + project + suffix, { method, headers: { ...headers, "Content-Type": "application/json" }, redirect: "error", signal: AbortSignal.timeout(15000), ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    if (!response.ok) throw new LoomError("EXTERNAL_TOOL_FAILED", `${target.provider} returned HTTP ${response.status}; request was not recorded as successful.`);
    return response.json();
  }
  function normalized(raw: any): ReviewRequest {
    const number = raw.number ?? raw.iid;
    const url = raw.html_url ?? raw.web_url;
    const head = raw.head?.ref ?? raw.source_branch;
    const targetBase = raw.base?.ref ?? raw.target_branch;
    if (!Number.isSafeInteger(number) || typeof url !== "string" || typeof head !== "string" || typeof targetBase !== "string") throw new LoomError("INVALID_OUTPUT", "Invalid review host response.");
    if (head !== target.head || targetBase !== target.base) throw new LoomError("CONFLICT", "Selected review request has different source or target branches.");
    return { number, url, head, base: targetBase };
  }
  const adapter: ReviewAdapter = {
    async find() {
      if (target.number !== undefined) return normalized(await api("GET", `/${target.number}`));
      const query = target.provider === "github"
        ? new URLSearchParams({ state: "open", head: `${target.repository.split("/")[0]}:${target.head}`, base: target.base, per_page: "100" })
        : new URLSearchParams({ state: "opened", source_branch: target.head, target_branch: target.base, per_page: "100" });
      const list = await api("GET", `?${query}`);
      if (!Array.isArray(list)) throw new LoomError("INVALID_OUTPUT", "Invalid review host list response.");
      if (list.length > 1) throw new LoomError("CONFLICT", "Several review requests match; define a number in the target.");
      return list[0] ? normalized(list[0]) : undefined;
    },
    async create(body) {
      const raw = target.provider === "github"
        ? { title: target.title, body, head: target.head, base: target.base, draft: target.draft }
        : { title: target.draft && !/^draft:/i.test(target.title) ? `Draft: ${target.title}` : target.title, description: body, source_branch: target.head, target_branch: target.base };
      return normalized(await api("POST", "", raw));
    },
    async update(number, body) {
      const raw = target.provider === "github" ? { title: target.title, body } : { title: target.draft && !/^draft:/i.test(target.title) ? `Draft: ${target.title}` : target.title, description: body };
      return normalized(await api(target.provider === "github" ? "PATCH" : "PUT", `/${number}`, raw));
    },
  };
  return adapter;
}

export async function publishReview(target: ReviewTarget, body: string, adapter: ReviewAdapter) {
  if (!target.allowWrites) throw new LoomError("POLICY_VIOLATION", "Review writes are disabled. Set allowWrites on this target after reviewing the preview.");
  const existing = await adapter.find();
  const request = existing ? await adapter.update(existing.number, body) : await adapter.create(body);
  return { action: existing ? "updated" : "created", request };
}
